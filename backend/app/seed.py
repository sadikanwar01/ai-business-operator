def ensure_demo_workspace() -> tuple[dict, dict]:
    """Return the demo user + workspace, creating and seeding them if needed."""
    user = query_one("SELECT * FROM users WHERE email = ?", (DEMO_EMAIL,))
    workspace = query_one("SELECT * FROM workspaces WHERE slug = ?", ("my-agency",))

    if user and workspace:
        return user, workspace

    stamp = now()

    if not user:
        user_id = new_id("usr")
        execute(
            """INSERT INTO users (id, email, name, password_hash, role, avatar_hue, created_at)
               VALUES (?,?,?,?,?,?,?)""",
            (user_id, DEMO_EMAIL, "Sadik", hash_password(DEMO_PASSWORD), "owner", "24", stamp),
        )
        user = query_one("SELECT * FROM users WHERE id = ?", (user_id,))

    if not workspace:
        workspace_id = new_id("wsp")
        execute(
            "INSERT INTO workspaces (id, name, slug, plan, created_at) VALUES (?,?,?,?,?)",
            (workspace_id, "My Agency", "my-agency", "Business", stamp),
        )
        execute(
            "INSERT INTO workspace_members (workspace_id, user_id, role) VALUES (?,?,?)",
            (workspace_id, user["id"], "owner"),
        )
        workspace = query_one("SELECT * FROM workspaces WHERE id = ?", (workspace_id,))

    seed_knowledge(workspace["id"])
    seed_integrations(workspace["id"])
    return user, workspace


def seed_knowledge(workspace_id: str) -> None:
    if query_one("SELECT COUNT(*) AS n FROM knowledge_items WHERE workspace_id = ?", (workspace_id,))["n"]:
        return
    stamp = now()
    for index, (category, title, content) in enumerate(KNOWLEDGE):
        execute(
            """INSERT INTO knowledge_items (id, workspace_id, category, key, title, content, order_index,
                   created_at, updated_at) VALUES (?,?,?,?,?,?,?,?,?)""",
            (new_id("knw"), workspace_id, category, category, title, content, index, stamp, stamp),
        )


def seed_integrations(workspace_id: str) -> None:
    if query_one("SELECT COUNT(*) AS n FROM integrations WHERE workspace_id = ?", (workspace_id,))["n"]:
        return
    stamp = now()
    for index, (category, name, description, status, provider) in enumerate(INTEGRATIONS):
        execute(
            """INSERT INTO integrations (id, workspace_id, category, name, description, status, provider,
                   config, order_index, updated_at) VALUES (?,?,?,?,?,?,?,?,?,?)""",
            (new_id("int"), workspace_id, category, name, description, status, provider,
             json.dumps({}), index, stamp),
        )


def _backdate(mission_id: str, hours_ago: int) -> None:
    """Move a mission and its activity into the recent past."""
    when = (datetime.now(timezone.utc) - timedelta(hours=hours_ago)).isoformat(timespec="seconds")
    execute("UPDATE missions SET created_at = ?, started_at = ? WHERE id = ?", (when, when, mission_id))
    execute(
        "UPDATE activity_logs SET created_at = ? WHERE mission_id = ?", (when, mission_id)
    )


async def seed_demo_missions() -> None:
    """Create the preloaded demo missions (one complete, one in flight)."""
    from .agents.operator import run_mission_now
    from .repository import create_mission

    user = query_one("SELECT * FROM users WHERE email = ?", (DEMO_EMAIL,))
    workspace = query_one("SELECT * FROM workspaces WHERE slug = ?", ("my-agency",))
    if not user or not workspace:
        return
    if query_one("SELECT COUNT(*) AS n FROM missions WHERE workspace_id = ?", (workspace["id"],))["n"]:
        return

    # ---- Mission 1: the completed reference mission ---------------------
    mission_id = create_mission(
        workspace_id=workspace["id"],
        created_by=user["id"],
        title="Healthcare Lead Generation",
        goal="Find 10 healthcare businesses in India that are likely to need a new website.",
        industry="Healthcare",
        location="India",
        target_count=10,
        desired_action="Personalized Outreach",
        target_audience="Hospitals and multi-speciality clinics",
        desired_result="Qualified opportunities with prepared outreach",
        mode="demo",
        provider="demo",
        source="demo",
    )
    outcome = await run_mission_now(mission_id, workspace["id"], resume=False, pace=0)
    if outcome.get("status") != "completed":
        raise RuntimeError(f"Reference mission failed to seed: {outcome.get('error')}")
    _backdate(mission_id, 6)
    _finalise_reference_mission(mission_id, workspace["id"])

    # ---- Mission 2: an in-flight mission the operator can resume -------
    second_id = create_mission(
        workspace_id=workspace["id"],
        created_by=user["id"],
        title="Multi-Speciality Hospital Outreach - Maharashtra",
        goal="Find multi-speciality hospitals in Maharashtra that need a faster, modern website.",
        industry="Healthcare",
        location="Maharashtra",
        target_count=5,
        desired_action="Personalized Outreach",
        mode="demo",
        provider="demo",
        source="demo",
    )
    await run_mission_now(second_id, workspace["id"], resume=False, pace=0, max_steps=3)
    # Park the second mission mid-qualification so the workspace always has a
    # live mission on the dashboard that the operator can resume.
    set_step(second_id, "qualify", status="running", progress=0,
             detail="Scoring and ranking opportunities")
    set_agent(second_id, "Qualification", status="working",
              task="Scoring leads and removing weak records")
    _backdate(second_id, 1)


def _finalise_reference_mission(mission_id: str, workspace_id: str) -> None:
    """Approve part of the drafted outreach and schedule the follow-up queue."""
    messages = query(
        "SELECT * FROM outreach_messages WHERE mission_id = ? ORDER BY rowid", (mission_id,)
    )
    for index, message in enumerate(messages):
        if index < 12:
            execute(
                "UPDATE outreach_messages SET status = 'approved', updated_at = ? WHERE id = ?",
                (now(), message["id"]),
            )
            execute(
                "UPDATE leads SET status = 'contacted', last_activity = ? WHERE id = ?",
                (now(), message["lead_id"]),
            )

    # Six follow-ups are due today, three more are queued for tomorrow.
    due_today = [(0, 1), (1, 1), (1, 2), (2, 1), (3, 1), (4, 1)]
    for index, sequence in due_today:
        if index >= len(messages):
            continue
        message = messages[index]
        insert_follow_up(
            workspace_id, mission_id, message["lead_id"], message["id"],
            sequence=sequence, due_date=days_from_now(0), status="scheduled",
            note="Check for a reply to the first outreach." if sequence == 1
            else "Second touch - share the rebuild example.",
        )
    for index, offset in ((5, 1), (6, 1), (7, 2)):
        if index >= len(messages):
            continue
        message = messages[index]
        insert_follow_up(
            workspace_id, mission_id, message["lead_id"], message["id"],
            sequence=1, due_date=days_from_now(offset), status="scheduled",
            note="Scheduled follow-up on the approved draft.",
        )

    log_activity(
        workspace_id, mission_id, "Operator", "outreach.approved", "complete",
        "12 outreach messages were approved by the workspace owner and queued for sending.",
        {"count": 12},
    )
